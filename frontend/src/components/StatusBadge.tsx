import React from 'react';
import type { ServerStatus } from '../types';

const STATUS_STYLES: Record<ServerStatus, { dot: string; bg: string; text: string; label: string }> = {
  healthy: {
    dot: 'bg-emerald-500',
    bg: 'bg-emerald-50 border-emerald-200',
    text: 'text-emerald-700',
    label: 'Healthy',
  },
  warning: {
    dot: 'bg-amber-500',
    bg: 'bg-amber-50 border-amber-200',
    text: 'text-amber-800',
    label: 'Warning',
  },
  critical: {
    dot: 'bg-rose-500',
    bg: 'bg-rose-50 border-rose-200',
    text: 'text-rose-700',
    label: 'Critical',
  },
  offline: {
    dot: 'bg-slate-400',
    bg: 'bg-slate-100 border-slate-200',
    text: 'text-slate-600',
    label: 'Offline',
  },
};

export const StatusBadge: React.FC<{ status: ServerStatus }> = ({ status }) => {
  const cfg = STATUS_STYLES[status] || STATUS_STYLES.offline;
  return (
    <span
      className={`inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-medium border ${cfg.bg} ${cfg.text}`}
    >
      <span className={`w-1.5 h-1.5 rounded-full ${cfg.dot}`} />
      {cfg.label}
    </span>
  );
};

export const SeverityBadge: React.FC<{ severity: string }> = ({ severity }) => {
  const upper = severity.toUpperCase();
  let cls = 'bg-sky-50 border-sky-200 text-sky-700';
  if (upper === 'CRITICAL') cls = 'bg-rose-50 border-rose-200 text-rose-700';
  else if (upper === 'ERROR') cls = 'bg-red-50 border-red-200 text-red-700';
  else if (upper === 'WARNING') cls = 'bg-amber-50 border-amber-200 text-amber-800';
  else if (upper === 'DEBUG') cls = 'bg-slate-100 border-slate-200 text-slate-600';

  return (
    <span className={`inline-flex items-center px-2 py-0.5 rounded text-[11px] font-mono font-semibold border ${cls}`}>
      {upper}
    </span>
  );
};

export const DemoBadge: React.FC<{ className?: string }> = ({ className = '' }) => (
  <span
    title="Simulated metric generated by SentinelOps Demo Mode"
    className={`inline-flex items-center px-2 py-0.5 rounded text-[10px] font-mono font-semibold tracking-wide bg-sky-50 text-sky-700 border border-sky-200 ${className}`}
  >
    DEMO DATA
  </span>
);
